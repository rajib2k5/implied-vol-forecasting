"""Generate notebooks/*.ipynb from the specs in this file.

    uv run python tools/build_notebooks.py           # (re)write the notebooks
    uv run python tools/build_notebooks.py --check   # CI: exit 1 if any committed notebook is stale

WHY GENERATE NOTEBOOKS
    A .ipynb file is JSON that mixes code with run output, execution counts
    and random cell ids. Committed as is, every re-run makes a noisy diff and
    reviewers cannot see what changed. Here the notebook is a build product:

    * the cells are written below, as plain Python strings, so diffs are readable;
    * outputs are stripped (a notebook is committed without results);
    * the bytes are deterministic: nbformat 4.5 and later requires an id for
      every cell, and we derive it from the cell's position instead of letting
      nbformat make a random one.

    ``--check`` regenerates every notebook in memory and compares the bytes with
    the committed files. Edit the spec here, never the .ipynb by hand.
"""

