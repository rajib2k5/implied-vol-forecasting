# --------------------------------------------------------------------------
# Building and checking
# --------------------------------------------------------------------------


def build_notebook(cells: list[Cell]) -> nbformat.NotebookNode:
    """One notebook with stripped outputs and ids derived from cell position."""
    made = []
    for index, (kind, source) in enumerate(cells):
        # Ids only have to be unique inside one notebook. Position is stable
        # across rebuilds, so an unchanged spec gives unchanged bytes.
        cell_id = f"cell-{index:03d}"
        make = new_markdown_cell if kind == "markdown" else new_code_cell
        made.append(make(source, id=cell_id))
    return new_notebook(
        cells=made,
        # No language_info.version and no kernel name beyond "python3": those
        # would differ between machines and break byte-for-byte --check.
        metadata={
            "kernelspec": {"display_name": "Python 3 (ipykernel)", "language": "python", "name": "python3"},
            "language_info": {"name": "python"},
        },
    )


def render(cells: list[Cell]) -> bytes:
    """The exact bytes of the .ipynb file for ``cells``."""
    notebook = build_notebook(cells)
    nbformat.validate(notebook)  # raises if an id is missing or duplicated, etc.
    text = nbformat.writes(notebook)  # sorted keys, indent 1: deterministic
    return (text if text.endswith("\n") else text + "\n").encode("utf-8")


def generate() -> dict[str, bytes]:
    return {name: render(cells) for name, cells in NOTEBOOKS.items()}


def write(directory: Path) -> list[Path]:
    directory.mkdir(parents=True, exist_ok=True)
    written = []
    for name, blob in generate().items():
        (directory / name).write_bytes(blob)
        written.append(directory / name)
    return written


def check(directory: Path) -> list[str]:
    """Differences between the specs and the notebooks in ``directory``. Empty = in sync."""
    problems = []
    expected = generate()
    for name, blob in sorted(expected.items()):
        path = directory / name
        if not path.is_file():
            problems.append(f"missing: {path}")
        elif path.read_bytes() != blob:
            problems.append(f"stale: {path} differs from what the spec generates")
    # A notebook with no spec is a leftover or a hand-made file.
    for path in sorted(directory.glob("*.ipynb")) if directory.is_dir() else []:
        if path.name not in expected:
            problems.append(f"unexpected: {path} has no spec in tools/build_notebooks.py")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate notebooks/*.ipynb from the specs in this file.")
    parser.add_argument("--check", action="store_true", help="exit 1 if any committed notebook is out of date")
    args = parser.parse_args(argv)

    if args.check:
        problems = check(NOTEBOOKS_DIR)
        for problem in problems:
            print(problem, file=sys.stderr)
        if problems:
            print("run: uv run python tools/build_notebooks.py", file=sys.stderr)
            return 1
        print(f"ok: {len(NOTEBOOKS)} notebook(s) in {NOTEBOOKS_DIR} match their specs")
        return 0

    for path in write(NOTEBOOKS_DIR):
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
